#!/usr/bin/env python3
"""Sitewide restyle to the 2026 design (idempotent).

Every page defines the same palette tokens inline (--cream, --ink, --coral, --serif ...). Remapping
those values moves the whole site to the homepage's look without touching page structure:
white pages, navy ink, the accessible coral, cool light panels, Figtree headings, no handwriting
font, pill buttons. The homepage (generated by build-homepage-v3.py) and mockups are skipped."""
import glob, re

MAP = {
    "--cream": "#ffffff",            # page background
    "--cream2": "#f5f8fb",           # light panels, alternating bands
    "--warm": "#fff0e8",             # answer boxes, highlighted callouts
    "--ink": "#1b2836",
    "--dark": "#1b2836",             # dark footer and dark bands
    "--coral": "#cf461e",            # white text on it is 4.6:1
    "--coral-d": "#b23c17",
    "--mute": "#4a5563",
    "--faint": "#5d6773",
    "--line": "#e3e8ee",
    "--serif": "'Figtree','Source Sans 3',-apple-system,sans-serif",
    "--hand": "'Source Sans 3',-apple-system,sans-serif",
}
SKIP = ("index.html", "turning-65/index.html")   # generated pages carry the 2026 tokens already
changed = []
for p in sorted(glob.glob("**/index.html", recursive=True)):
    if p.startswith(("mockups/", "dist/")) or p in SKIP:
        continue
    h = open(p, encoding="utf-8").read(); o = h

    def fix_style(m):
        css = m.group(1)
        def fix_root(r):
            body = r.group(1)
            for k, v in MAP.items():
                body = re.sub(rf'({re.escape(k)})\s*:\s*[^;]+;', rf'\1:{v};', body)
            return ":root{" + body + "}"
        css = re.sub(r':root\s*\{(.*?)\}', fix_root, css, count=1, flags=re.S)
        # pill buttons for the page's main .btn class
        css = re.sub(r'(\.btn\{[^}]*?border-radius:)\d+px', r'\g<1>999px', css)
        # handwriting font family references that bypass the token
        css = css.replace("'Caveat',cursive", "'Source Sans 3',sans-serif")
        return "<style>" + css + "</style>"
    h = re.sub(r'<style>(.*?)</style>', fix_style, h, flags=re.S)

    # stop loading fonts the design no longer uses (Figtree comes from site.css)
    def fix_fonts(m):
        url = m.group(1)
        fams = re.findall(r'family=([^&"]+)', url)
        keep = [f for f in fams if not f.startswith(("Fraunces", "Caveat"))]
        if not keep or len(keep) == len(fams):
            return m.group(0)
        new = "https://fonts.googleapis.com/css2?" + "&".join("family=" + f for f in keep) + "&display=swap"
        return m.group(0).replace(url, new)
    h = re.sub(r'<link[^>]*?href="(https://fonts\.googleapis\.com/css2\?[^"]+)"[^>]*>', fix_fonts, h)
    h = h.replace('font-family="Fraunces,Georgia,serif"', 'font-family="Figtree,Source Sans 3,sans-serif"')
    h = h.replace('<meta name="theme-color" content="#1f1d1a">', '<meta name="theme-color" content="#cf461e">')
    if h != o:
        open(p, "w", encoding="utf-8").write(h); changed.append(p)
print("pages restyled:", len(changed))
